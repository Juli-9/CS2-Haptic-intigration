HapticController::HapticController(uint8_t pin1, uint8_t pin2)
{
    motor1_pin = pin1;
    motor2_pin = pin2;

    pinMode(motor1_pin, OUTPUT);
    pinMode(motor2_pin, OUTPUT);

    off();

    loop_tim.start(1.0 / float(SERIAL_COM_FREQ) * 1000);
}

void HapticController::off(){
    analogWrite(motor1_pin, 0);
    analogWrite(motor2_pin, 0);
}

void HapticController::update_position(float pos)
{
    position = constrain(pos, 0.0f, 1.0f);
}

void HapticController::update_intensity(float intens){
    intensity = constrain(intens, 0.0f, 1.0f);
}

void HapticController::update_pattern(HapticController::Pattern p, int period, bool oneShot){
    pattern_idx = 0;
    pattern = p;

    pattern_period_ms = period;

    one_shot = oneShot;

    t.start(period);
}

void HapticController::process(){

    float p = t.progress();

    if (p >= 1.0f) {
        if(one_shot){
            this->off();
            return;
        }
        t.reset();
        p = 0.0f;
    }

    pattern_idx = (uint8_t)(p * 255.0f);

    float pos = position;
    float gain1 = pos;
    float gain2 = 1.0 - pos;

    uint8_t idx1 = (uint8_t)(gain1 * 255.0f);
    uint8_t idx2 = (uint8_t)(gain2 * 255.0f);

    float base1 = logLUT[idx1] / 255.0f;
    float base2 = logLUT[idx2] / 255.0f;

    float value1 = base1 * intensity * pattern_bias();
    float value2 = base2 * intensity * pattern_bias();

    uint8_t pwm1 = (uint8_t)(value1 * 255.0f);
    uint8_t pwm2 = (uint8_t)(value2 * 255.0f);

    if(loop_tim.isFinished()){

        Serial.print(pwm1);
        Serial.print(",");
        Serial.println(pwm2);

        loop_tim.reset();
    }


    // Serial.print("pos=");        
    // Serial.print(position, 6);

    // Serial.print(" base1=");
    // Serial.print(base1, 6);

    // Serial.print(" intensity=");
    // Serial.print(intensity, 6);

    // Serial.print(" bias=");
    // Serial.print(pattern_bias(), 6);

    // Serial.print(" value1=");
    // Serial.println(value1, 6);

    analogWrite(motor1_pin, pwm1);
    analogWrite(motor2_pin, pwm2);
}

float HapticController::pattern_bias(){
    switch (pattern) {
        case HapticController::Pattern::Constant: 
            return 1.0f;
        break;

        case HapticController::Pattern::SinePulse: 
            return float(sinLUT[pattern_idx]) / 255.0f;
        break;

        case HapticController::Pattern::SawUp: 
            return float(sawUpLUT[pattern_idx]) / 255.0f;
        break;

        
        case HapticController::Pattern::SawDown: 
            return float(sawDownLUT[pattern_idx]) / 255.0f;
        break;
                
        case HapticController::Pattern::HeavyShot: 
            return float(heavyShotLUT[pattern_idx]) / 255.0f;
        break;

        default:
            // Wird ausgeführt, wenn kein Case passt
            break;
    }
    return 1.0;
}